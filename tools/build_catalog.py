"""Build the public install catalog from explicitly selected own addons."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    addons = json.loads((ROOT / 'addons.json').read_text(encoding='utf-8'))
    lines = ['-- Generated by tools/build_catalog.py. Only our own addon folders are listed.',
             'local _, FT = ...', 'FT.addonCatalog = {']
    for addon in addons:
        fields = ', '.join(f'{key} = {json.dumps(value, ensure_ascii=False)}'
                           for key, value in addon.items())
        lines.append('    {' + fields + '},')
    lines.append('}')
    (ROOT / 'ForeverTools/AddonCatalog.lua').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    catalog = {'schema': 1, 'addons': []}
    for addon in addons:
        folder = ROOT / addon['folder']
        assert (folder / (folder.name + '.toc')).is_file(), folder
        files = [{'path': p.relative_to(folder).as_posix(),
                  'sha256': hashlib.sha256(p.read_bytes()).hexdigest()}
                 for p in sorted(folder.rglob('*')) if p.is_file()]
        catalog['addons'].append(dict(addon, files=files))
    (ROOT / 'catalog.json').write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    build()
